// History: the Outlook moving with the tray lowered, then the tray rising, then held.
const puppeteer = require('puppeteer-core')
const src = require('fs').readFileSync(require('path').join(__dirname,'shoot.cjs'),'utf8')
eval(src.slice(src.indexOf('const DAY'), src.indexOf('const SCENES')).replace(/^const /gm,'global.'))
;(async () => {
  const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--hide-scrollbars', '--autoplay-policy=no-user-gesture-required', '--mute-audio'] })
  const p = await b.newPage(); await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 1.5, isMobile: true, hasTouch: true })
  await p.evaluateOnNewDocument((s) => { if (!sessionStorage.getItem('seeded')) { localStorage.clear(); for (const k in s) localStorage.setItem(k, s[k]); sessionStorage.setItem('seeded', '1') } }, global.store)
  await p.goto('http://localhost:8120/', { waitUntil: 'networkidle0', timeout: 120000 }); await new Promise(r=>setTimeout(r,3000))
  await (await p.waitForSelector('[data-testid="home-history"]')).click(); await new Promise(r=>setTimeout(r,3500))
  const rec = await p.screencast({ path: `${process.env.OUT}/history.webm`, ffmpegPath: process.env.FFMPEG })
  await new Promise(r=>setTimeout(r,3500))
  await (await p.waitForSelector('[data-testid="history-tray-lower"]')).click()
  await new Promise(r=>setTimeout(r,8000)); await rec.stop()
  await p.screenshot({ path: `${process.env.OUT}/history-raised.png` }); await b.close()
})().catch(e=>{console.error(e.message);process.exit(1)})
